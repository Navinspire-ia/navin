export const AWS_TEMPLATES_CATALOG_URL =
  "https://navinagent.s3.eu-north-1.amazonaws.com/templates/v1/catalog.json";

export const STUDIO_CATEGORIES = new Set(["chat", "rag", "agents", "search"]);

export type TemplateBucket = "chat" | "rag" | "agents" | "business";

/** One real gallery bucket per template. Business first, then RAG / Chat / Agents IA. */
export function templateBucket(row: { kind: string; category: string }): TemplateBucket {
  if (row.kind === "business") return "business";
  if (row.category === "rag") return "rag";
  if (row.category === "chat" || row.category === "search") return "chat";
  return "agents";
}

export async function fetchAwsAppTemplatesCatalog(): Promise<AppTemplateSummary[] | null> {
  try {
    const response = await fetch(AWS_TEMPLATES_CATALOG_URL, { cache: "no-store" });
    if (!response.ok) return null;
    const payload = (await response.json()) as { templates?: AppTemplateSummary[] };
    if (!Array.isArray(payload.templates) || payload.templates.length === 0) return null;
    return payload.templates;
  } catch {
    return null;
  }
}

export function mergeAppTemplates(
  remote: AppTemplateSummary[],
  fallback: AppTemplateSummary[] = APP_TEMPLATES_FALLBACK,
): AppTemplateSummary[] {
  const bySlug = new Map<string, AppTemplateSummary>();
  for (const row of fallback) bySlug.set(row.slug, row);
  for (const row of remote) bySlug.set(row.slug, row);
  return [...bySlug.values()].sort((a, b) => {
    if (a.featured !== b.featured) return a.featured ? -1 : 1;
    const aStudio = STUDIO_CATEGORIES.has(a.category) ? 0 : 1;
    const bStudio = STUDIO_CATEGORIES.has(b.category) ? 0 : 1;
    if (aStudio !== bStudio) return aStudio - bStudio;
    return a.name.localeCompare(b.name);
  });
}
