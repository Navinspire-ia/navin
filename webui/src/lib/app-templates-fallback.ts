import type { AppTemplateSummary } from "@/lib/types";

const UNIVERSAL = [
  "research-agent",
  "analytics-agent",
  "document-agent",
  "knowledge-agent",
  "automation-agent",
];

function card(
  // Every field this function fills in itself is omitted here and offered back
  // as optional. featured has to be in that list like audit_status: omitting it
  // is what makes the default below reachable, and intersecting a required
  // property with an optional one leaves it required.
  row: Omit<
    AppTemplateSummary,
    | "status"
    | "audit_status"
    | "installed"
    | "local_cache"
    | "can_publish"
    | "aws_key"
    | "universal_agents"
    | "featured"
  > & {
    featured?: boolean;
    audit_status?: AppTemplateSummary["audit_status"];
  },
): AppTemplateSummary {
  const { audit_status, featured, ...rest } = row;
  return {
    status: "source",
    audit_status: audit_status ?? "pending",
    installed: false,
    local_cache: false,
    can_publish: false,
    aws_key: `templates/v1/${rest.slug}.tar.gz`,
    aws_url: `https://navinagent.s3.eu-north-1.amazonaws.com/templates/v1/${rest.slug}.tar.gz`,
    universal_agents: UNIVERSAL,
    featured: featured ?? false,
    ...rest,
  };
}

