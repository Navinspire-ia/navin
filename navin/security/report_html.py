_STEP_SPLIT = re.compile(r"\s*(?:->|→|=>|\n)\s*")


def _labels(lang: str) -> dict[str, str]:
    return _LABELS.get(lang, _LABELS["en"])


def _chip(severity: str) -> str:
    sev = (severity or "medium").lower()
    color = _SEV_COLORS.get(sev, _SEV_COLORS["medium"])
    return (
        f'<span style="display:inline-block;padding:2px 10px;border-radius:999px;'
        f'background:{color};color:#fff;font-size:12px;font-weight:600;'
        f'text-transform:uppercase;letter-spacing:.03em">{esc(sev)}</span>'
    )


def _refs(item: dict[str, Any]) -> str:
    parts = []
    if item.get("cwe"):
        parts.append(f"<strong>{esc(item.get('cwe'))}</strong>")
    if item.get("owasp"):
        parts.append(esc(item.get("owasp")))
    return " · ".join(parts)


def _text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, (list, tuple)):
        return "\n".join(str(part).strip() for part in value if str(part).strip())
    if isinstance(value, dict):
        return json.dumps(value, ensure_ascii=False, indent=1)
    return str(value).strip()


def _steps(value: Any) -> str:
    """A trigger flow as numbered steps: a list, or a string joined with -> or new lines."""
    if isinstance(value, (list, tuple)):
        parts = [str(part).strip() for part in value if str(part).strip()]
    else:
        text = _text(value)
        parts = [part for part in _STEP_SPLIT.split(text) if part] if text else []
    if not parts:
        return ""
    if len(parts) == 1:
        return f"<p>{esc(parts[0])}</p>"
    return '<ol class="steps">' + "".join(f"<li>{esc(part)}</li>" for part in parts) + "</ol>"


def _bullets(value: Any) -> str:
    if isinstance(value, (list, tuple)):
        rows = [str(part).strip() for part in value if str(part).strip()]
        return "<ul>" + "".join(f"<li>{esc(row)}</li>" for row in rows) + "</ul>" if rows else ""
    text = _text(value)
    return f"<p>{esc(text)}</p>" if text else ""


def _confidence(value: Any) -> str:
    if isinstance(value, bool) or value is None or value == "":
        return ""
    if isinstance(value, (int, float)):
        return f"{round(value * 100) if value <= 1 else round(value)} %"
    return str(value)


def _fix_of(item: dict[str, Any]) -> str:
    return _text(item.get("remediation") or item.get("recommendation") or item.get("minimal_fix") or item.get("fix"))


def _impact_of(item: dict[str, Any]) -> str:
    return _text(item.get("impact") or item.get("explanation"))


def _location(item: dict[str, Any]) -> str:
    loc = str(item.get("file_path") or item.get("endpoint") or "")
    line = item.get("line")
    return f"{loc}:{line}" if loc and isinstance(line, int) else (loc or "n/a")


def _card(idx: int, item: dict[str, Any], lang: str) -> str:
    labels = _labels(lang)
    status = str(item.get("status") or "").lower()
    meta = [f"<span><strong>{labels['location']}:</strong> <code>{esc(_location(item))}</code></span>"]
    kind = item.get("vulnerability_type") or item.get("category")
    if kind:
        meta.append(f"<span><strong>{labels['type']}:</strong> {esc(kind)}</span>")
    if status:
        shown = _STATUS.get(lang, _STATUS["en"]).get(status, status)
        meta.append(f"<span><strong>{labels['status']}:</strong> {esc(shown)}</span>")
    confidence = _confidence(item.get("confidence"))
    if confidence:
        meta.append(f"<span><strong>{labels['confidence']}:</strong> {esc(confidence)}</span>")
    refs = _refs(item)
    if refs:
        meta.append(f"<span>{refs}</span>")
    if item.get("id"):
        meta.append(f"<span><strong>{labels['rule']}:</strong> <code>{esc(item.get('id'))}</code></span>")

    sections: list[str] = []
    flow = _steps(item.get("trigger_flow") or item.get("attack_path"))
    story = _text(item.get("exploit_scenario") or item.get("scenario"))
    if flow or story:
        story_html = f"<p>{esc(story)}</p>" if story else ""
        sections.append(f"<h4>{labels['scenario']}</h4>{flow}{story_html}")
    impact = _impact_of(item)
    if impact:
        sections.append(f"<h4>{labels['impact']}</h4><p>{esc(impact)}</p>")
    proof = _text(item.get("existing_code") or item.get("evidence") or item.get("source_sink"))
    if proof:
        sections.append(f"<h4>{labels['proof']}</h4><pre>{esc(proof)}</pre>")
    payload = _text(item.get("malicious_input_example"))
    sketch = _text(item.get("poc_sketch"))
    if payload or sketch:
        payload_html = f"<p><strong>{labels['payload']}:</strong></p><pre>{esc(payload)}</pre>" if payload else ""
        sketch_html = f"<p>{esc(sketch)}</p>" if sketch else ""
        sections.append(f"<h4>{labels['example']}</h4><div class=\"proof\">{payload_html}{sketch_html}</div>")
    fix = _fix_of(item)
    sections.append(f"<h4>{labels['fix']}</h4><div class=\"fix\">{esc(fix or labels['no_fix'])}</div>")
    counter = _bullets(item.get("counter_examples") or item.get("counter_example"))
    if counter:
        sections.append(f"<h4>{labels['counter']}</h4>{counter}")

    title = item.get("summary") or item.get("title") or item.get("id")
    return f"""
<article class="card">
  <header>
    {_chip(str(item.get('severity')))}
    <h3>#{idx} {esc(title)}</h3>
  </header>
  <div class="meta">{''.join(meta)}</div>
  {''.join(sections)}
</article>
"""


def render_security_report_html(
    *,
    findings: list[dict[str, Any]],
    root: str | Path,
    kind: str = "full",
    tools: list[dict[str, Any]] | None = None,
    title: str = "Security review",
    report_name: str | None = None,
    lang: str = "en",
    coverage: dict[str, Any] | None = None,
    limits: list[str] | None = None,
    data_name: str | None = None,
) -> str:
    """Build a self-contained HTML security report (inline CSS, no JS)."""
    labels = _labels(lang)
    enriched = enrich_findings_with_poc(list(findings))
    enriched.sort(key=lambda f: _SEV_RANK.get(str(f.get("severity") or "medium").lower(), 2))
    counts = severity_counts(enriched)
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    report_file = report_name or "security-report-*.html"

    summary_bits = []
    for sev in ("critical", "high", "medium", "low", "info"):
        n = counts.get(sev, 0)
        if n:
            summary_bits.append(f"<li>{_chip(sev)} <strong>{n}</strong></li>")
    summary_list = (
        f"<ul class=\"sev\">{''.join(summary_bits)}</ul>" if summary_bits
        else f"<p class=\"muted\">{labels['no_findings']}</p>"
    )

    tool_rows = ""
    for tool in tools or []:
        if not isinstance(tool, dict):
            continue
        avail = labels["yes"] if tool.get("available") else labels["no"]
        tool_rows += (
            "<tr>"
            f"<td>{esc(tool.get('tool'))}</td>"
            f"<td>{esc(avail)}</td>"
            f"<td>{esc(tool.get('count', tool.get('error', '')))}</td>"
            "</tr>"
        )
    if not tool_rows:
        tool_rows = f"<tr><td colspan='3' class='muted'>{labels['none_engines']}</td></tr>"

    coverage_html = ""
    if coverage:
        complete = labels["yes"] if coverage.get("audit_complete") else labels["no"]
        coverage_html = f"""
    <div class="panel">
      <p><strong>{labels['coverage']}</strong></p>
      <p>{esc(coverage.get('referential', ''))}</p>
      <p>{labels['verified']}: <strong>{esc(coverage.get('verified_coverage', 0))} %</strong>
        · {labels['complete']}: <strong>{esc(complete)}</strong></p>
    </div>"""

    cards = [_card(idx, item, lang) for idx, item in enumerate(enriched, start=1)]

    remediations = []
    plan_items = [
        f for f in enriched
        if str(f.get("severity") or "").lower() in {"critical", "high", "medium"}
    ][:12] or enriched[:5]
    for i, item in enumerate(plan_items, start=1):
        sev = str(item.get("severity") or "medium").lower()
        remediations.append(
            f"""
<div class="choice">
  <h3>#{i} - {esc(item.get('summary') or item.get('title') or item.get('id'))}</h3>
  <p class="meta">{_chip(sev)} <span>{labels['effort']} {esc(_EFFORT.get(sev, 'M'))}</span>
    <span><code>{esc(_location(item))}</code></span></p>
  <p><strong>{labels['risk']}:</strong> {esc(_impact_of(item)[:260])}</p>
  <p><strong>{labels['first']}:</strong> {esc(_fix_of(item) or labels['no_fix'])}</p>
</div>
"""
        )

    limits_html = ""
    rows = [str(row).strip() for row in limits or [] if str(row).strip()]
    if rows:
        limits_html = (
            f"<h2>{labels['limits']}</h2><div class=\"panel\"><ul>"
            + "".join(f"<li>{esc(row)}</li>" for row in rows)
            + "</ul></div>"
        )

    deliv_rows = [(report_file, "HTML", labels["html_desc"])]
    if data_name:
        deliv_rows.append((data_name, "JSON", labels["json_desc"]))
    deliv = deliverables_table(deliv_rows)
    plan_html = "".join(remediations) or f"<p class='muted'>{labels['nothing']}</p>"
    cards_html = "".join(cards) or f"<p class='muted'>{labels['no_findings']}</p>"

    return f"""<!DOCTYPE html>
<html lang="{esc(lang)}">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width, initial-scale=1"/>
<title>{esc(title)}</title>
<style>{EXPERT_CSS}
table {{ width:100%; border-collapse:collapse; font-size:.9rem; }}
th,td {{ text-align:left; padding:.45rem .5rem; border-bottom:1px solid var(--line); }}
ul.sev {{ list-style:none; padding:0; margin:.4rem 0 0; display:flex; flex-wrap:wrap; gap:.6rem 1rem; }}
</style>
</head>
<body>
<div class="wrap">
  <header>
    <p class="muted">{labels['brand']} · {esc(kind)}</p>
    <h1>{esc(title)}</h1>
    <p class="muted">{labels['scope']}: <code>{esc(str(root))}</code> · {esc(ts)}</p>
  </header>

  <h2>{labels['summary']}</h2>
  <div class="summary">
    <div class="panel">
      <p><strong>{len(enriched)}</strong> {labels['findings_count']}</p>
      {summary_list}
    </div>
    <div class="panel">
      <p><strong>{labels['engines']}</strong></p>
      <table>
        <thead><tr><th>{labels['engine']}</th><th>{labels['ran']}</th><th>{labels['detail']}</th></tr></thead>
        <tbody>{tool_rows}</tbody>
      </table>
    </div>
  </div>
  {coverage_html}

  <h2>{labels['findings']}</h2>
  {cards_html}

  <h2>{labels['plan']}</h2>
  <p class="muted">{labels['plan_hint']}</p>
  {plan_html}

  {limits_html}

  <h2>{labels['deliverables']}</h2>
  <div class="panel">{deliv}</div>

  <footer>{labels['footer']}</footer>
</div>
</body>
</html>
"""


def write_security_report(
    root: Path,
    *,
    findings: list[dict[str, Any]],
    kind: str = "full",
    tools: list[dict[str, Any]] | None = None,
    title: str = "Security review",
    lang: str = "en",
    coverage: dict[str, Any] | None = None,
    limits: list[str] | None = None,
) -> Path:
    """Write ``security-report-<timestamp>.html`` and its ``.json`` under ``root``; return the HTML path."""
    root = root.expanduser().resolve(strict=False)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    name = f"security-report-{stamp}.html"
    path = root / name
    data_path = path.with_suffix(".json")
    html_doc = render_security_report_html(
        findings=findings,
        root=root,
        kind=kind,
        tools=tools,
        title=title,
        report_name=name,
        lang=lang,
        coverage=coverage,
        limits=limits,
        data_name=data_path.name,
    )
    path.write_text(html_doc, encoding="utf-8")
    data = {
        "title": title,
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "root": str(root),
        "coverage": coverage,
        "limits": list(limits or []),
        "findings": list(findings),
    }
    data_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    return path
