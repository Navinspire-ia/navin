"""Generate Prometheus recording and multi-window burn-rate alert rules for one SLO.

Usage:
    burn_rate_rules.py --name <slo-name> --target 99.9 \
        --good '<PromQL counter selector for good events>' \
        --total '<PromQL counter selector for all events>' \
        [--service <svc>] [--window-days 30] [--labels team=payments,tier=1]
        [--out rules.yml] [--json]

    burn_rate_rules.py --spec <slo.json> [--out rules.yml]

``--good`` and ``--total`` are counter selectors without a range, for example
``http_requests_total{job="api",code!~"5.."}`` and ``http_requests_total{job="api"}``.
The script wraps them in ``rate(...[window])`` for each window.

The JSON spec form accepts ``{"name", "target", "good", "total", "service",
"window_days", "labels"}`` (same meaning as the flags).

Output: a Prometheus rule file (YAML written with plain string formatting)
with recording rules ``slo:sli_error:ratio_rate<window>`` for 5m, 30m, 1h, 2h,
6h, 1d, 3d, ``slo:error_budget:remaining`` and the four workbook alerts
(14.4x 1h/5m page, 6x 6h/30m page, 3x 1d/2h ticket, 1x 3d/6h ticket).

Exit codes:
    0  rules generated
    2  usage or input error (bad target, missing expressions, unreadable spec)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

WINDOWS: tuple[str, ...] = ("5m", "30m", "1h", "2h", "6h", "1d", "3d")

ALERTS: tuple[tuple[str, float, str, str], ...] = (
    ("page", 14.4, "1h", "5m"),
    ("page", 6.0, "6h", "30m"),
    ("ticket", 3.0, "1d", "2h"),
    ("ticket", 1.0, "3d", "6h"),
)

NAME_RE = re.compile(r"^[a-zA-Z_][a-zA-Z0-9_\-]*$")


def yaml_quote(text: str) -> str:
    """Single-quote a YAML scalar (PromQL contains double quotes and braces)."""
    return "'" + text.replace("'", "''") + "'"


def parse_labels(raw: str | None) -> dict[str, str]:
    labels: dict[str, str] = {}
    if not raw:
        return labels
    for pair in raw.split(","):
        pair = pair.strip()
        if not pair:
            continue
        if "=" not in pair:
            raise ValueError(f"label {pair!r} must be key=value")
        key, value = pair.split("=", 1)
        labels[key.strip()] = value.strip()
    return labels


def build_rules(name: str, target_pct: float, good: str, total: str, service: str, window_days: int, labels: dict[str, str]) -> str:
    target = target_pct / 100.0
    budget = round(1.0 - target, 10)
    budget_text = f"{budget:.10g}"
    window = f"{window_days}d"
    base_labels = {"sloth_slo": name, "slo_service": service, **labels}
    label_lines = "".join(f"          {k}: {yaml_quote(v)}\n" for k, v in base_labels.items())

    out: list[str] = []
    out.append(f"# Generated by burn_rate_rules.py for SLO {name} ({target_pct}% over {window})\n")
    out.append("groups:\n")
    out.append(f"  - name: slo-{name}-recordings\n")
    out.append("    rules:\n")
    for w in WINDOWS:
        expr = f"1 - (sum(rate({good}[{w}])) / sum(rate({total}[{w}])))"
        out.append(f"      - record: slo:sli_error:ratio_rate{w}\n")
        out.append(f"        expr: {yaml_quote(expr)}\n")
        out.append("        labels:\n")
        out.append(label_lines)
    out.append("      - record: slo:objective:ratio\n")
    target_text = f"{target:.10g}"
    out.append(f"        expr: {yaml_quote(target_text)}\n")
    out.append("        labels:\n")
    out.append(label_lines)
    out.append("      - record: slo:error_budget:ratio\n")
    out.append(f"        expr: {yaml_quote(budget_text)}\n")
    out.append("        labels:\n")
    out.append(label_lines)
    window_expr = (
        f"1 - ((1 - (sum(increase({good}[{window}])) / sum(increase({total}[{window}])))) / {budget_text})"
    )
    out.append("      - record: slo:error_budget:remaining\n")
    out.append(f"        expr: {yaml_quote(window_expr)}\n")
    out.append("        labels:\n")
    out.append(label_lines)

    out.append(f"  - name: slo-{name}-alerts\n")
    out.append("    rules:\n")
    for severity, factor, long_w, short_w in ALERTS:
        alert_name = f"SLO{''.join(p.capitalize() for p in re.split(r'[-_]', name))}ErrorBudgetBurn{long_w.upper()}"
        selector = "{" + f'sloth_slo="{name}"' + "}"
        expr = (
            f"(slo:sli_error:ratio_rate{long_w}{selector} > ({factor} * {budget_text})) "
            f"and (slo:sli_error:ratio_rate{short_w}{selector} > ({factor} * {budget_text}))"
        )
        hours_to_exhaust = round(window_days * 24 / factor, 1)
        out.append(f"      - alert: {alert_name}\n")
        out.append(f"        expr: {yaml_quote(expr)}\n")
        out.append("        for: 2m\n")
        out.append("        labels:\n")
        out.append(f"          severity: {severity}\n")
        out.append(f"          slo: {yaml_quote(name)}\n")
        out.append(f"          service: {yaml_quote(service)}\n")
        for k, v in labels.items():
            out.append(f"          {k}: {yaml_quote(v)}\n")
        out.append("        annotations:\n")
        out.append(f"          summary: {yaml_quote(f'{service}: {name} burning error budget at {factor}x over {long_w} (short window {short_w})')}\n")
        out.append(
            f"          description: {yaml_quote(f'Burn rate {factor}x consumes the {window} budget in about {hours_to_exhaust} hours. Current long-window error ratio: {{{{ $value | humanizePercentage }}}}.')}\n"
        )
        out.append(f"          runbook: {yaml_quote(f'https://runbooks.example.internal/slo/{name}')}\n")
    return "".join(out)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Prometheus recording and burn-rate alert rules for one SLO.")
    parser.add_argument("--spec", help="JSON file with name, target, good, total, service, window_days, labels")
    parser.add_argument("--name", help="SLO name, e.g. api-availability")
    parser.add_argument("--target", type=float, help="SLO target in percent, e.g. 99.9")
    parser.add_argument("--good", help="PromQL counter selector for good events")
    parser.add_argument("--total", help="PromQL counter selector for all events")
    parser.add_argument("--service", default=None, help="service label (default: the SLO name)")
    parser.add_argument("--window-days", type=int, default=None, help="SLO window in days (default 30)")
    parser.add_argument("--labels", default=None, help="extra labels key=value,key=value")
    parser.add_argument("--out", default=None, help="write the rules to this file instead of stdout")
    parser.add_argument("--json", action="store_true", help="print a JSON summary (file, rule count, alerts) instead of the YAML text")
    return parser


def resolve_spec(args: argparse.Namespace) -> dict[str, Any]:
    spec: dict[str, Any] = {}
    if args.spec:
        payload = json.loads(Path(args.spec).read_text(encoding="utf-8"))
        if not isinstance(payload, dict):
            raise ValueError("spec must be a JSON object")
        spec.update(payload)
    for key in ("name", "target", "good", "total", "service", "window_days", "labels"):
        value = getattr(args, key)
        if value is not None:
            spec[key] = value
    missing = [k for k in ("name", "target", "good", "total") if not spec.get(k)]
    if missing:
        raise ValueError("missing " + ", ".join(f"--{m}" for m in missing))
    spec["target"] = float(spec["target"])
    if not 0 < spec["target"] < 100:
        raise ValueError("target must be between 0 and 100 (exclusive)")
    if not NAME_RE.match(str(spec["name"])):
        raise ValueError("name must match [a-zA-Z_][a-zA-Z0-9_-]*")
    spec["service"] = str(spec.get("service") or spec["name"])
    spec["window_days"] = int(spec.get("window_days") or 30)
    if spec["window_days"] < 1:
        raise ValueError("window_days must be >= 1")
    raw_labels = spec.get("labels")
    if isinstance(raw_labels, dict):
        spec["labels"] = {str(k): str(v) for k, v in raw_labels.items()}
    else:
        spec["labels"] = parse_labels(raw_labels if isinstance(raw_labels, str) else None)
    return spec


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        spec = resolve_spec(args)
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    text = build_rules(
        str(spec["name"]), spec["target"], str(spec["good"]), str(spec["total"]), spec["service"], spec["window_days"], spec["labels"]
    )
    if args.out:
        try:
            Path(args.out).write_text(text, encoding="utf-8")
        except OSError as exc:
            print(f"error: cannot write {args.out}: {exc}", file=sys.stderr)
            return 2
    summary = {
        "slo": spec["name"],
        "target_pct": spec["target"],
        "window_days": spec["window_days"],
        "recording_rules": len(WINDOWS) + 3,
        "alerts": [f"{sev} {factor}x {lw}/{sw}" for sev, factor, lw, sw in ALERTS],
        "out": args.out,
    }
    if args.json:
        print(json.dumps(summary, indent=2))
    elif not args.out:
        print(text, end="")
    else:
        print(f"wrote {args.out}: {summary['recording_rules']} recording rules, {len(ALERTS)} alerts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
