"""Catalog of the bundled plugins and skills (``navin/marketplace.json``).

The catalog is generated by ``scripts/build_skill_marketplace.py``. Each
plugin maps workflow steps to the slash command, agent or skill to use, so the
agent can pick the right extension for every step. Paths inside it are
relative to the navin package folder.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

PACKAGE_DIR = Path(__file__).resolve().parent.parent
MARKETPLACE_PATH = PACKAGE_DIR / "marketplace.json"
_cache: tuple[float, dict[str, Any]] | None = None


def load_marketplace(path: Path | None = None) -> dict[str, Any]:
    """Parsed catalog, ``{}`` when it is missing or broken (cached by mtime)."""
    global _cache
    target = path or MARKETPLACE_PATH
    try:
        mtime = target.stat().st_mtime
    except OSError:
        return {}
    if path is None and _cache is not None and _cache[0] == mtime:
        return _cache[1]
    try:
        data = json.loads(target.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    if path is None:
        _cache = (mtime, data)
    return data


def marketplace_summary(path: Path | None = None, *, detailed: frozenset[str] | None = None) -> str:
    """Prompt lines: where the catalog is and which step uses what ('' when absent).

    ``detailed`` keeps the step routes only for those plugins; the others are
    named on one line and read from the catalog when a task needs them.
    """
    target = path or MARKETPLACE_PATH
    data = load_marketplace(path)
    plugins = [p for p in data.get("plugins") or [] if isinstance(p, dict) and p.get("name")]
    if not plugins:
        return ""
    lines = [
        f"Bundled plugins (catalog `{target}`, paths relative to `{target.parent}`; "
        "it also lists every skill with when to use it). For each step, use what it names:"
    ]
    if detailed is not None:
        others = [p["name"] for p in plugins if p["name"] not in detailed]
        plugins = [p for p in plugins if p["name"] in detailed]
    else:
        others = []
    for plugin in plugins:
        steps = "; ".join(
            f"{s.get('step')} -> {s.get('use')}"
            for s in plugin.get("steps") or []
            if isinstance(s, dict) and s.get("use")
        )
        lines.append(f"- **{plugin['name']}**: {steps or plugin.get('description', '')}")
    if others:
        lines.append("- Also bundled (read the catalog before using one): " + ", ".join(others) + ".")
    return "\n".join(lines)
